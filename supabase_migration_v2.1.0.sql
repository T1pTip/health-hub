CREATE TABLE IF NOT EXISTS knowledge_base (
  id           BIGSERIAL PRIMARY KEY,
  source_name  TEXT NOT NULL,                -- "דיאטת קיטו", "אימונים אסף", etc
  category     TEXT NOT NULL DEFAULT 'general', -- diet|health|workouts|medical|general
  title        TEXT NOT NULL,
  summary      TEXT NOT NULL,                -- תקציר קצר (נכנס ל-context)
  full_content TEXT,                          -- תוכן מלא (לעיון בלבד)
  tags         TEXT[] DEFAULT '{}',
  source_url   TEXT,
  is_active    BOOLEAN DEFAULT TRUE,
  priority     INT DEFAULT 5,                 -- 1-10, גבוה = חשוב יותר
  created_at   TIMESTAMPTZ DEFAULT NOW(),
  updated_at   TIMESTAMPTZ DEFAULT NOW()
);

